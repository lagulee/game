// =============================================================
// waves.js : 웨이브 구성을 모아 두는 파일
// -------------------------------------------------------------
// WAVES 배열의 한 칸 = 웨이브 하나.
// 한 칸 안에는 "어떤 적을 몇 마리" 묶음을 원하는 만큼 적는다.
//   { type: "basic", count: 10 }  → enemies.js 의 basic 적 10마리
//
// 예) 기본 적 8마리가 나온 뒤 다른 적 3마리가 나오는 웨이브:
//   [{ type: "basic", count: 8 }, { type: "다른적이름", count: 3 }]
//
// 적은 적힌 순서대로 한 마리씩 WAVE_SPAWN_INTERVAL 초 간격으로 나온다.
// 배열에 칸을 하나 더 추가하면 웨이브가 하나 늘어난다!
// =============================================================

// 웨이브 중에 적이 하나씩 나타나는 간격 (초)
